import {e2eArtifact} from './helpers/environment.mjs';
import { test, expect } from './helpers/browser.js';
import { readFileSync } from 'node:fs';

test('real Vue → HTTP → PostgreSQL login, required password change, reload and logout', async ({ page }) => {
  const fixture: { email: string; userId: string; temporaryPassword: string } = JSON.parse(readFileSync(e2eArtifact('e2e-credentials.json'), 'utf8'));
  await page.goto('/my/overview');
  await expect(page.getByRole('heading', { name: '登录工作空间' })).toBeVisible();
  await page.getByLabel('邮箱', { exact: true }).fill(fixture.email);
  await page.getByLabel('密码', { exact: true }).fill('wrong-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByText('邮箱或密码不正确', { exact: true })).toBeVisible();
  await page.getByLabel('密码', { exact: true }).fill(fixture.temporaryPassword);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '请先设置新密码', exact: true })).toBeVisible();
  await page.goto('/my/overview');
  await expect(page).toHaveURL(/\/change-password/);
  await page.getByLabel('当前密码', { exact: true }).fill(fixture.temporaryPassword);
  await page.getByLabel('新密码', { exact: true }).fill('e2e-regular-test-password');
  await page.getByLabel('确认新密码', { exact: true }).fill('different-test-password');
  await page.getByRole('button', { name: '保存并继续' }).click();
  await expect(page.getByText('两次输入的新密码不一致', { exact: true })).toBeVisible();
  await page.getByLabel('确认新密码', { exact: true }).fill('e2e-regular-test-password');
  await page.getByRole('button', { name: '保存并继续' }).click();
  await expect(page).toHaveURL(/\/my\/overview$/);
  await expect(page.getByRole('navigation').getByRole('link', { name: '组织分析', exact: true })).toHaveCount(0);
  await expect(page.getByRole('heading', { name: '我的使用概览', exact: true })).toBeVisible();
  await expect(page.getByRole('banner').getByText(fixture.email, { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: '我的使用概览', exact: true })).toBeVisible();
  await expect(page.getByRole('banner').getByText(fixture.email, { exact: true })).toBeVisible();
  const csrfRejected = await page.request.post('/api/v1/auth/logout');
  expect(csrfRejected.status()).toBe(403);
  await page.getByRole('button', { name: '退出登录' }).click();
  await expect(page.getByRole('heading', { name: '登录工作空间' })).toBeVisible();
  await page.goto('/organization?role=super');
  await expect(page).toHaveURL(/\/login/);
  expect((await page.request.get('/api/v1/me?role=super')).status()).toBe(401);
});
